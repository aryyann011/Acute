import typer
import sys
from loguru import logger
from agent.rag.scanner import RepositoryScanner
from agent.rag.ingest import CodeChunker
from agent.rag.embedder import VectorEmbedder
from agent.rag.vector_store import QdrantDB
from agent.core.memory import ContextManager
from agent.tools.coder import Coder
from agent.tools.patcher import CodePatcher

app = typer.Typer()

@app.callback()
def Colourization():
    """Acute : Autonomous codebase patching agent"""
    logger.remove()

    logger.add(
        sys.stderr,
        format="<green>{time:HH:mm:ss}</green> |<level>{level: <8}</level> |<cyan>{message}</cyan>",
        level="INFO"
    )

    logger.add("logs/agent_run.log", rotation="5 MB", level="DEBUG")

@app.command()
def index(path: str = "."):
    """
    Index the codebase into the local vector database.
    """
    logger.info(f"Starting ingestion process for directory: {path}")
    logger.debug(f"DEBUG: Initializing file scanner at absolute path for {path}")
    
    scanner = RepositoryScanner(path)
    valid_files = scanner.get_tracked_files()
    
    if not valid_files:
        logger.warning("No files found to process. Aborting.")
    chunker = CodeChunker()
    chunks = chunker.process_files(valid_files)
    
    if not chunks:
        logger.warning("No chunks generated. Aborting.")
        raise typer.Exit(code=1)

    embedder = VectorEmbedder()
    embedded_chunks = embedder.process_chunks(chunks)
    
    if embedded_chunks:
        logger.success("Printing a sample embedded chunk:")
        print("\n" + "="*60)
        print(f"File: {embedded_chunks[0]['filepath']}")
        print(f"Function/Class Name: {embedded_chunks[0]['name']}")
        print(f"Vector Dimension (Size): {len(embedded_chunks[0]['vector'])}")
        print(f"Vector Sample (first 5 floats): {embedded_chunks[0]['vector'][:5]}")
        print("="*60 + "\n")

    logger.info("Connecting to local Qdrant Vector DB...")
    db = QdrantDB()
    db.insert_chunks(embedded_chunks)
    
    logger.success(f"Phase 2 Complete. {len(embedded_chunks)} chunks securely persisted to disk.")

@app.command()
def fix(bug: str):
    """
    Run the autonomous agent loop to fix a bug report.
    """
    if not bug.strip():
        logger.error("Nothing to fix: the prompt is empty.")
        raise typer.Exit(code=1)

    logger.info(f"Initialising patch agent for bug: '{bug}'")

    embedder = VectorEmbedder()
    query_vector = embedder.embed_text(bug)

    if not query_vector:
        logger.error("Bug report could not be vectorised.")
        raise typer.Exit(code=1)

    db = QdrantDB()
    closest_chunks = db.search(query_vector, limit=7)

    if not closest_chunks:
        logger.error("Qdrant returned 0 matching chunks. Make sure you ran 'acute index' first.")
        raise typer.Exit(code=1)

    context = ContextManager().assemble_xml_context(closest_chunks)

    coder = Coder()
    patch = coder.generate_patch(bug, context)

    if not patch:
        logger.error("No patch generated by the Coder.")
        raise typer.Exit(code=1)

    patcher = CodePatcher()
    total = len(patch.edits)
    logger.info(f"Generated {total} edit(s). Beginning transactional patch application.")

    # Decision 2 - all-or-nothing: snapshot every target file ONCE, before any edit runs.
    # (Re-snapshotting later would back up a file that earlier edits may have modified.)
    snapshots = {}
    for filepath in dict.fromkeys(edit.filepath for edit in patch.edits):
        backup_path = patcher.snapshot_file(filepath)
        if backup_path is None:
            logger.error(f"Snapshot failed for {filepath}. Transaction aborted before any edit.")
            raise typer.Exit(code=1)
        snapshots[filepath] = backup_path

    # Decision 1 - the CLI is the orchestrator: loop over edits and splice each one.
    for index, edit in enumerate(patch.edits, start=1):
        logger.info(
            f"Applying edit {index}/{total} -> {edit.filepath} :: {edit.target_function}"
            f" ({edit.explanation[:60]}...)"
        )
        ok = patcher.patch_file(
            edit.filepath, edit.target_function, edit.fixed_code, create_backup=False
        )

        if not ok:
            logger.error(
                f"Edit {index} failed ('{edit.target_function}' in {edit.filepath})."
                " Rolling back every change made in this run."
            )
            for filepath, backup_path in snapshots.items():
                patcher.restore_file(filepath, backup_path)
            logger.error("Transaction rolled back. Nothing was left half-patched.")
            raise typer.Exit(code=1)

    logger.success(
        f"Transaction committed: {total}/{total} edit(s) applied."
        " (.bak snapshots kept in place for manual review.)"
    )

    logger.info(f"Patch generation complete for bug: '{bug}'.")

if __name__ == "__main__":
    app()